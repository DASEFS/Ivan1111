function getArticles() {
    const stored = localStorage.getItem('ivan_articles');
    if (stored) { try { return JSON.parse(stored); } catch(e) { return defaultArticles; } }
    localStorage.setItem('ivan_articles', JSON.stringify(defaultArticles));
    return defaultArticles;
}

function getSettings() {
    const stored = localStorage.getItem('ivan_settings');
    if (stored) { try { return JSON.parse(stored); } catch(e) {} }
    return { siteName: "Ivan.miller", whatsapp: "+8618363882260", email: "EstheerEagler@gmail.com", replyHours: "12", mapEmbed: "" };
}

function applyLang(lang) {
    currentLang = lang;
    localStorage.setItem('ivan_lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) { el.textContent = translations[lang][key]; }
    });
    const btn = document.getElementById('langBtn');
    if (btn) btn.textContent = lang === 'en' ? '中文 / EN' : 'EN / 中文';
    renderArticles();
}

function toggleLang() { applyLang(currentLang === 'en' ? 'zh' : 'en'); }

function getCategoryLabel(cat, lang) {
    const key = 'category_' + cat;
    return translations[lang] && translations[lang][key] ? translations[lang][key] : cat;
}

function formatDate(dateStr, lang) {
    try {
        const d = new Date(dateStr);
        if (lang === 'zh') { return d.getFullYear() + '年' + (d.getMonth()+1) + '月' + d.getDate() + '日'; }
        return d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    } catch(e) { return dateStr; }
}

function renderArticles() {
    const grid = document.getElementById('articleGrid');
    if (!grid) return;
    const articles = getArticles().sort((a,b) => new Date(b.date) - new Date(a.date));
    const lang = currentLang;
    if (articles.length === 0) {
        grid.innerHTML = '<div class="article-empty"><p>' + (translations[lang].magazine_empty || 'No articles yet.') + '</p></div>';
        document.getElementById('statArticles').textContent = '0';
        return;
    }
    document.getElementById('statArticles').textContent = articles.length;
    grid.innerHTML = articles.map(article => {
        const title = lang === 'zh' ? (article.title_zh || article.title_en) : article.title_en;
        const excerpt = lang === 'zh' ? (article.excerpt_zh || article.excerpt_en) : article.excerpt_en;
        const coverStyle = article.cover ? 'background-image:url(' + article.cover + ');background-size:cover;background-position:center;' : '';
        const coverImg = article.cover ? '<img src="' + article.cover + '" alt="' + title + '" loading="lazy">' : '';
        return '<div class="article-card" onclick="openArticle(' + article.id + ')">' +
            '<div class="article-cover" style="' + coverStyle + '">' + coverImg + '</div>' +
            '<div class="article-body">' +
                '<div class="article-meta"><span>' + getCategoryLabel(article.category, lang) + '</span><span>' + formatDate(article.date, lang) + '</span></div>' +
                '<h3>' + title + '</h3><p>' + excerpt + '</p>' +
            '</div></div>';
    }).join('');
}

function openArticle(id) {
    const articles = getArticles();
    const article = articles.find(a => a.id === id);
    if (!article) return;
    const lang = currentLang;
    const title = lang === 'zh' ? (article.title_zh || article.title_en) : article.title_en;
    const content = lang === 'zh' ? (article.content_zh || article.content_en) : article.content_en;
    document.getElementById('modalTitle').textContent = title;
    document.getElementById('modalContent').innerHTML = content;
    document.getElementById('modalCategory').textContent = getCategoryLabel(article.category, lang);
    document.getElementById('modalDate').textContent = formatDate(article.date, lang);
    const cover = document.getElementById('modalCover');
    cover.innerHTML = article.cover ? '<img src="' + article.cover + '" alt="' + title + '">' : '';
    document.getElementById('articleModal').classList.add('open');
    document.body.style.overflow = 'hidden';
}

function closeArticleModal() {
    document.getElementById('articleModal').classList.remove('open');
    document.body.style.overflow = '';
}

function closeModal(e) { if (e.target.id === 'articleModal') closeArticleModal(); }

function handleCookie(accept) {
    localStorage.setItem('ivan_cookie_consent', accept ? 'accepted' : 'declined');
    document.getElementById('cookieBanner').classList.remove('show');
}

function checkCookieConsent() {
    const consent = localStorage.getItem('ivan_cookie_consent');
    if (!consent) { setTimeout(() => { document.getElementById('cookieBanner').classList.add('show'); }, 800); }
}

function handleNavScroll() {
    const navbar = document.getElementById('navbar');
    if (window.scrollY > 50) { navbar.classList.add('scrolled'); } else { navbar.classList.remove('scrolled'); }
    const sections = ['home', 'magazine', 'about', 'contact', 'privacy'];
    const scrollPos = window.scrollY + 120;
    sections.forEach(id => {
        const section = document.getElementById(id);
        if (section) {
            const top = section.offsetTop;
            const bottom = top + section.offsetHeight;
            const link = document.querySelector('.nav-links a[href="#' + id + '"]');
            if (link && scrollPos >= top && scrollPos < bottom) {
                document.querySelectorAll('.nav-links a').forEach(a => a.classList.remove('active'));
                link.classList.add('active');
            }
        }
    });
}

function toggleMobileMenu() { document.getElementById('mobileMenu').classList.toggle('open'); }

document.addEventListener('keydown', function(e) { if (e.key === 'Escape') closeArticleModal(); });

document.addEventListener('DOMContentLoaded', function() {
    document.getElementById('footerYear').textContent = new Date().getFullYear();
    applyLang(currentLang);
    checkCookieConsent();
    window.addEventListener('scroll', handleNavScroll);
    handleNavScroll();
});
